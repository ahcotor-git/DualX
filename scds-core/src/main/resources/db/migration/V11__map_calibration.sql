-- ============================================================================
-- V11 —— 底图标定生效时刻
--
-- 问题：t_map.uwb_meta 只记录标定的**内容**（四角像素坐标 + 两个长宽基准），不记录
-- 这次标定是**什么时候**做的。现场重压底图、换场地或挪动基站之后，指挥端无从判断一份
-- 标定是不是已经过期；而 UwbCalibrationService 的 appliedAt 只活在进程内存里（见该类
-- 「状态是进程内的」一段），重启即丢——两条路都没有可查的时间证据。
--
-- 本迁移只补一列「标定生效时刻」，不含任何业务逻辑：
--   calibrated_at   这张底图最近一次把标定写进 uwb_meta 的时刻（UTC 挂钟值）
--
-- 与 uwb_meta 的绑定：内容与时刻由**同一次写入**产生（MapLedgerService.saveUwbMeta），
-- 因此现场可以读作「uwb_meta 齐备 ⟺ calibrated_at 非空」。NULL 表示从来没标定过。
--
-- 版本号说明：原设计预留号为 V8，而 V9、V10 已应用、V8 从未创建。直接补 V8 会成为低于
-- 当前版本的未应用迁移并受 Flyway 校验/顺序限制，故取**下一递增版本 V11**；
-- 不改任何历史迁移，也不开启 out-of-order（同 V10 的口径）。
-- ============================================================================

ALTER TABLE t_map
    ADD COLUMN calibrated_at DATETIME(3) NULL
        COMMENT '最近一次标定写入 uwb_meta 的时刻（UTC）；NULL 表示从未标定，不随改名换型刷新';
